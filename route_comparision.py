
import pandas as pd
from math import radians, sin, cos, sqrt, atan2

# Same sample locations used in route_optimization.py
locations = pd.DataFrame({
    "Location": ["Warehouse", "A", "B", "C", "D"],
    "Latitude": [18.5204, 18.5314, 18.5074, 18.5642, 18.4900],
    "Longitude": [73.8567, 73.8446, 73.8325, 73.7769, 73.8100]
})

def distance(lat1, lon1, lat2, lon2):
    radius = 6371

    lat1, lon1, lat2, lon2 = map(
        radians, [lat1, lon1, lat2, lon2]
    )

    dlat = lat2 - lat1
    dlon = lon2 - lon1

    a = (
        sin(dlat / 2) ** 2
        + cos(lat1) * cos(lat2) * sin(dlon / 2) ** 2
    )

    return 2 * radius * atan2(sqrt(a), sqrt(1 - a))


def calculate_distance(route):
    total = 0

    for i in range(len(route) - 1):
        a = locations[locations["Location"] == route[i]].iloc[0]
        b = locations[locations["Location"] == route[i + 1]].iloc[0]

        total += distance(
            a["Latitude"], a["Longitude"],
            b["Latitude"], b["Longitude"]
        )

    return total


# Baseline: original order
baseline_route = ["Warehouse", "A", "B", "C", "D", "Warehouse"]

# Optimized route generated by Nearest Neighbor
optimized_df = pd.read_csv("sample_optimized_route.csv")
optimized_route = optimized_df["Location"].tolist()

baseline_distance = calculate_distance(baseline_route)
optimized_distance = calculate_distance(optimized_route)

saving = baseline_distance - optimized_distance
saving_percent = (saving / baseline_distance) * 100

print("===== ROUTE COMPARISON =====")
print("Baseline route:", " -> ".join(baseline_route))
print("Nearest Neighbor route:", " -> ".join(optimized_route))
print(f"Baseline distance: {baseline_distance:.2f} km")
print(f"Nearest Neighbor distance: {optimized_distance:.2f} km")
print(f"Distance difference: {saving:.2f} km")
print(f"Distance difference (%): {saving_percent:.2f}%")